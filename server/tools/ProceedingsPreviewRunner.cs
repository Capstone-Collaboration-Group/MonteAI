        /// <summary>Nearest directory (from the working directory or the binaries) that holds the header strip.</summary>
        private static string FindContentRoot()
        {
            foreach (var start in new[] { Directory.GetCurrentDirectory(), AppContext.BaseDirectory })
            {
                var dir = new DirectoryInfo(start);
                while (dir != null)
                {
                    if (File.Exists(Path.Combine(dir.FullName, "assets", "images", "proceedings-header.png")))
                        return dir.FullName;
                    dir = dir.Parent;
                }
            }

            return Directory.GetCurrentDirectory();
        }

        private sealed class FakeRepository(ProceedingsDataDto data) : IProceedingsRepository
        {
            public Task<ProceedingsDataDto?> GetProceedingsDataAsync(Guid thesisId, CancellationToken cancellationToken)
                => Task.FromResult<ProceedingsDataDto?>(data);

            public Task<bool> IsStudentThesisMemberAsync(Guid thesisId, string studentId, CancellationToken cancellationToken)
                => Task.FromResult(true);

            public Task<IReadOnlyDictionary<string, string>> GetDisplayNamesAsync(
                IEnumerable<string> userIds,
                CancellationToken cancellationToken)
            {
                IReadOnlyDictionary<string, string> names = new Dictionary<string, string>
                {
                    ["adv-1"] = "Prof. Elmer Lim",
                };
                return Task.FromResult(names);
            }
        }

        private sealed class FakeAnnotationReader(List<ProceedingsAnnotationDto> comments) : IAnnotationReader
        {
            public Task<IReadOnlyList<ProceedingsAnnotationDto>> ReadAsync(
                Guid thesisId,
                IReadOnlyList<Guid> versionIds,
                CancellationToken cancellationToken)
                => Task.FromResult<IReadOnlyList<ProceedingsAnnotationDto>>(comments);
        }

        private sealed class PreviewEnvironment(string contentRoot) : IWebHostEnvironment
        {
            public string ApplicationName { get; set; } = "server";
            public IFileProvider ContentRootFileProvider { get; set; } = new NullFileProvider();
            public string ContentRootPath { get; set; } = contentRoot;
            public string EnvironmentName { get; set; } = "Development";
            public string WebRootPath { get; set; } = contentRoot;
            public IFileProvider WebRootFileProvider { get; set; } = new NullFileProvider();
        }
