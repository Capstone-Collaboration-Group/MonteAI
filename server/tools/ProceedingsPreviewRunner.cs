    /// <summary>
    /// Renders the proceedings form from fixture data so the layout can be eyeballed
    /// without a database or a signed-in user:
    ///
    ///   dotnet run --project server -- --proceedings-preview [out.pdf] [--blank] [--role "Panel Member"]
    ///
    /// --blank drops every panel comment, so Section V prints its five empty rows;
    /// --role is the value recorded as "Generated by:" (default "Panel Chairperson").
    /// </summary>
    public static class ProceedingsPreviewRunner
    {
        public static async Task<int> RunAsync(string[] args)
        {
            var output = args
                .Skip(1)
                .FirstOrDefault(arg => !arg.StartsWith("--", StringComparison.Ordinal))
                ?? Path.Combine(Directory.GetCurrentDirectory(), "proceedings-preview.pdf");

            var blank = args.Contains("--blank", StringComparer.OrdinalIgnoreCase);

            var role = "Panel Chairperson";
            var roleIndex = Array.FindIndex(args, arg => arg.Equals("--role", StringComparison.OrdinalIgnoreCase));
            if (roleIndex >= 0 && roleIndex + 1 < args.Length) role = args[roleIndex + 1];

            var data = BuildFixture();
            var service = new ProceedingsService(
                new FakeRepository(data),
                new FakeAnnotationReader(BuildComments(blank)),
                new PreviewEnvironment(FindContentRoot()),
                NullLogger<ProceedingsService>.Instance);

            var pdf = await service.GenerateProceedingsAsync(data.ThesisId, role, CancellationToken.None);
            if (pdf == null)
            {
                Console.Error.WriteLine("Proceedings preview failed: fixture was not found.");
                return 1;
            }

            var full = Path.GetFullPath(output);
            Directory.CreateDirectory(Path.GetDirectoryName(full)!);
            await File.WriteAllBytesAsync(full, pdf);
            Console.WriteLine($"Proceedings preview written to {full} ({pdf.Length:N0} bytes)");
            return 0;
        }

